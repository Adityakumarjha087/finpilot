package com.finpilot.seed;

import com.finpilot.anomaly.AnomalyService;
import com.finpilot.auth.AuthService;
import com.finpilot.budget.Budget;
import com.finpilot.budget.BudgetRepository;
import com.finpilot.goal.Goal;
import com.finpilot.goal.GoalRepository;
import com.finpilot.importing.ImportDtos.ParsedRow;
import com.finpilot.importing.ImportService;
import com.finpilot.ml.MlClient;
import com.finpilot.ml.MlUnavailableException;
import com.finpilot.user.Role;
import com.finpilot.user.User;
import com.finpilot.user.UserRepository;
import java.math.BigDecimal;
import java.time.Clock;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;

/**
 * Seeds a demo user with 12 months of synthetic transactions (generated by the ML service's synthetic data
 * generator and pushed through the normal import pipeline, so categories come from the real model), plus
 * budgets, goals and an anomaly scan. Idempotent: does nothing if the demo user already exists.
 */
@Component
@ConditionalOnProperty(prefix = "finpilot.seed", name = "enabled", havingValue = "true")
public class DemoDataSeeder implements ApplicationRunner {
    public static final String DEMO_EMAIL = "demo@finpilot.dev";
    public static final String DEMO_PASSWORD = "DemoPass123!";
    public static final String ADMIN_EMAIL = "admin@finpilot.dev";
    public static final String ADMIN_PASSWORD = "AdminPass123!";
    private static final Logger log = LoggerFactory.getLogger(DemoDataSeeder.class);

    private final UserRepository users;
    private final AuthService auth;
    private final MlClient ml;
    private final ImportService imports;
    private final BudgetRepository budgets;
    private final GoalRepository goals;
    private final AnomalyService anomalies;
    private final Clock clock;
    private final ZoneId zone;

    public DemoDataSeeder(UserRepository users, AuthService auth, MlClient ml, ImportService imports,
                          BudgetRepository budgets, GoalRepository goals, AnomalyService anomalies, Clock clock,
                          ZoneId appZone) {
        this.users = users;
        this.auth = auth;
        this.ml = ml;
        this.imports = imports;
        this.budgets = budgets;
        this.goals = goals;
        this.anomalies = anomalies;
        this.clock = clock;
        this.zone = appZone;
    }

    @Override
    public void run(ApplicationArguments args) throws InterruptedException {
        if (users.existsByEmailIgnoreCase(ADMIN_EMAIL) && users.existsByEmailIgnoreCase(DEMO_EMAIL)) {
            log.info("demo data already present, skipping seed");
            return;
        }
        if (!users.existsByEmailIgnoreCase(ADMIN_EMAIL)) {
            auth.createUser(ADMIN_EMAIL, ADMIN_PASSWORD, "FinPilot Admin", Role.ADMIN);
        }
        List<Map<String, Object>> rows = fetchSynthetic();
        User demo = auth.createUser(DEMO_EMAIL, DEMO_PASSWORD, "Demo User", Role.USER);
        demo.setOpeningBalance(new BigDecimal("150000.00"));
        users.save(demo);
        List<ParsedRow> parsed = new ArrayList<>();
        int i = 0;
        for (Map<String, Object> r : rows) {
            parsed.add(new ParsedRow(++i, LocalDateTime.parse((String) r.get("posted_at")), (String) r.get("description"),
                    new BigDecimal(String.valueOf(r.get("amount")))));
        }
        int[] counts = imports.persist(demo.getId(), null, parsed);
        budgets.saveAll(List.of(
                new Budget(demo.getId(), "Food", new BigDecimal("6000")),
                new Budget(demo.getId(), "Groceries", new BigDecimal("9000")),
                new Budget(demo.getId(), "Shopping", new BigDecimal("5000")),
                new Budget(demo.getId(), "Transport", new BigDecimal("4000")),
                new Budget(demo.getId(), "Entertainment", new BigDecimal("2500"))));
        LocalDate today = LocalDate.now(clock.withZone(zone));
        goals.saveAll(List.of(
                new Goal(demo.getId(), "Emergency fund", new BigDecimal("300000"), new BigDecimal("85000"),
                        today.plusMonths(10)),
                new Goal(demo.getId(), "Goa trip", new BigDecimal("60000"), new BigDecimal("12000"),
                        today.plusMonths(4))));
        try {
            var scan = anomalies.scan(demo.getId());
            log.info("seeded demo user: {} transactions, {} anomalies flagged", counts[0], scan.flagged());
        } catch (MlUnavailableException e) {
            log.warn("seeded demo user without anomaly scan: {}", e.getMessage());
        }
    }

    /** The ML service may still be starting; retry for up to ~2 minutes. */
    private List<Map<String, Object>> fetchSynthetic() throws InterruptedException {
        MlUnavailableException last = null;
        for (int attempt = 0; attempt < 40; attempt++) {
            try {
                return ml.syntheticTransactions(12, 42);
            } catch (MlUnavailableException e) {
                last = e;
                Thread.sleep(3000);
            }
        }
        throw last;
    }
}
